// Code generators for the tree produced by agent.recreate(). Output is generated markup, not the page's original source.
const DFGen = (() => {
  const VOID = new Set([
    'area',
    'base',
    'br',
    'col',
    'embed',
    'hr',
    'img',
    'input',
    'link',
    'meta',
    'source',
    'track',
    'wbr',
  ]);
  const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
  const escAttr = (s) => String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;');
  const ind = (n) => '  '.repeat(n);
  const cssSafe = (css) => String(css).replace(/</g, '\\3c '); // '<' is only valid inside CSS strings, where \3c is equivalent; blocks </style> breakout

  function html(node, depth = 0, opts = {}) {
    if (node.text != null) {
      const t = node.text;
      return /\S/.test(t) ? ind(depth) + esc(t.replace(/\s+/g, ' ').trim()) + '\n' : '';
    }
    const attrs = Object.entries(node.attrs)
      .map(([k, v]) => ` ${k}="${escAttr(v)}"`)
      .join('');
    const cls = node.cls ? ` class="${escAttr(node.cls)}"` : '';
    const root = depth === 0 && opts.root ? ' data-df-root' : '';
    const open = `<${node.tag}${cls}${attrs}${root}>`;
    if (VOID.has(node.tag)) return ind(depth) + open + '\n';
    const kids = node.children.map((c) => html(c, depth + 1, opts)).join('');
    if (!kids) return ind(depth) + open + `</${node.tag}>\n`;
    if (node.children.length === 1 && node.children[0].text != null)
      return (
        ind(depth) +
        open +
        esc(node.children[0].text.replace(/\s+/g, ' ').trim()) +
        `</${node.tag}>\n`
      );
    return ind(depth) + open + '\n' + kids + ind(depth) + `</${node.tag}>\n`;
  }

  const RESERVED = new Set(['annotation-xml', 'color-profile', 'font-face', 'font-face-src', 'font-face-uri', 'font-face-format', 'font-face-name', 'missing-glyph']);
  // A custom element name needs a hyphen and a letter first, and must not be a reserved SVG/MathML name.
  function elementName(s) {
    let n = String(s || '').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '') || 'component';
    if (!/^[a-z]/.test(n)) n = 'x-' + n;
    if (!n.includes('-')) n += '-part';
    return RESERVED.has(n) ? 'df-' + n : n;
  }
  const oneLine = (s) => String(s).replace(/[\r\n]+/g, ' ');
  const banner = (meta) =>
    meta
      ? `// Generated by DevForge ${oneLine(meta.tool)} from ${oneLine(meta.source)} on ${oneLine(meta.page)}.\n// Static markup and CSS from computed styles. Event handlers and page scripts were not copied.\n`
      : '';
  const camel = (s) => s.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
  const compName = (s) =>
    (s || 'Component')
      .replace(/(^|[^a-zA-Z0-9]+)([a-zA-Z0-9])/g, (_, __, c) => c.toUpperCase())
      .replace(/^[^A-Z]/, 'C$&');
  function jsxAttrKey(k) {
    const m = {
      class: 'className',
      for: 'htmlFor',
      tabindex: 'tabIndex',
      colspan: 'colSpan',
      rowspan: 'rowSpan',
      readonly: 'readOnly',
      maxlength: 'maxLength',
      autocomplete: 'autoComplete',
      crossorigin: 'crossOrigin',
      srcset: 'srcSet',
      viewbox: 'viewBox',
      'stroke-width': 'strokeWidth',
      'stroke-linecap': 'strokeLinecap',
      'stroke-linejoin': 'strokeLinejoin',
      'fill-rule': 'fillRule',
      'clip-rule': 'clipRule',
      'clip-path': 'clipPath',
      'stop-color': 'stopColor',
      'xlink:href': 'xlinkHref',
    };
    return m[k] || (k.startsWith('data-') || k.startsWith('aria-') ? k : camel(k));
  }
  // Attributes that React takes as a flag. Any other empty attribute keeps its empty string,
  // because a bare name in JSX means true.
  const JSX_BOOL = new Set(['allowfullscreen', 'async', 'autofocus', 'autoplay', 'checked', 'controls', 'default', 'defer', 'disabled', 'formnovalidate', 'hidden', 'loop', 'multiple', 'muted', 'novalidate', 'open', 'readonly', 'required', 'reversed', 'selected']);
  function jsx(node, depth = 1) {
    if (node.text != null) {
      const t = node.text.replace(/\s+/g, ' ').trim();
      return t ? ind(depth) + '{' + JSON.stringify(t) + '}\n' : '';
    }
    const attrs = Object.entries(node.attrs)
      .filter(([k]) => k !== 'xmlns')
      .map(([k, v]) => (v === '' && JSX_BOOL.has(k) ? ` ${jsxAttrKey(k)}` : ` ${jsxAttrKey(k)}="${escAttr(v)}"`))
      .join('');
    const cls = node.cls ? ` className="${escAttr(node.cls)}"` : '';
    const open = `<${node.tag}${cls}${attrs}`;
    if (VOID.has(node.tag)) return ind(depth) + open + ' />\n';
    const kids = node.children.map((c) => jsx(c, depth + 1)).join('');
    if (!kids) return ind(depth) + open + ' />\n';
    return ind(depth) + open + '>\n' + kids + ind(depth) + `</${node.tag}>\n`;
  }

  function twArb(style) {
    return Object.entries(style)
      .map(([p, v]) => `[${p}:${v.replace(/\s+/g, '_').replace(/[[\]]/g, '')}]`)
      .join(' ');
  }
  function tailwind(node, depth = 0, opts = {}) {
    if (node.text != null)
      return /\S/.test(node.text)
        ? ind(depth) + esc(node.text.replace(/\s+/g, ' ').trim()) + '\n'
        : '';
    const attrs = Object.entries(node.attrs)
      .map(([k, v]) => ` ${k}="${escAttr(v)}"`)
      .join('');
    const cls = Object.keys(node.style).length ? ` class="${escAttr(twArb(node.style))}"` : '';
    const open = `<${node.tag}${cls}${attrs}${depth === 0 && opts.root ? ' data-df-root' : ''}>`;
    if (VOID.has(node.tag)) return ind(depth) + open + '\n';
    const kids = node.children.map((c) => tailwind(c, depth + 1, opts)).join('');
    return ind(depth) + open + (kids ? '\n' + kids + ind(depth) : '') + `</${node.tag}>\n`;
  }

  function page(tree, css, title, opts = {}) {
    return `<!DOCTYPE html>\n<html lang="en">\n<head>\n  <meta charset="utf-8">\n  <meta name="viewport" content="width=device-width, initial-scale=1">\n  <title>${esc(title || 'Recreated component')}</title>\n  <style>\n${opts.reset === false ? '' : '    html,body{margin:0}\n'}${cssSafe(
      css
    )
      .split('\n')
      .map((l) => (l ? '    ' + l : l))
      .join(
        '\n'
      )}\n  </style>\n</head>\n<body>\n${html(tree, 1, { root: true })}</body>\n</html>\n`;
  }

  // The recreated tree as a JavaScript array literal: [tag, attributes, class, children, namespace].
  // Text becomes a plain string, and whitespace-only text is dropped, as in the HTML output.
  function treeLiteral(node, depth) {
    const pad = '  '.repeat(depth);
    if (node.text != null) return /\S/.test(node.text) ? pad + JSON.stringify(node.text.replace(/\s+/g, ' ').trim()) : '';
    const kids = node.children.map((c) => treeLiteral(c, depth + 1)).filter(Boolean);
    const head = pad + '[' + JSON.stringify(node.tag) + ', ' + JSON.stringify(node.attrs) + ', ' + (node.cls ? JSON.stringify(node.cls) : 'null') + ', [';
    const tail = node.ns === 'svg' ? ', "svg"]' : ']';
    if (!kids.length) return head + ']' + tail;
    return head + '\n' + kids.join(',\n') + '\n' + pad + ']' + tail;
  }

  function generate(rec, target, name, meta) {
    const nm = compName(name);
    const tree = rec.tree,
      css = rec.css;
    switch (target) {
      case 'html':
        return {
          files: [
            { path: 'index.html', data: page(tree, css, name) },
            { path: 'styles.css', data: css },
            { path: 'body.html', data: html(tree, 0) },
          ],
        };
      case 'react': {
        const body = jsx(tree, 2);
        return {
          files: [
            {
              path: `${nm}.jsx`,
              data: `${banner(meta)}import './${nm}.css';\n\nexport default function ${nm}() {\n  return (\n${body.replace(/\n$/, '')}\n  );\n}\n`,
            },
            { path: `${nm}.css`, data: css },
            {
              path: 'README.md',
              data: 'Generated React component (functional, no dependencies beyond React). Static markup only: event handlers and application state were not reconstructed.\n',
            },
          ],
        };
      }
      case 'vue': {
        const body = html(tree, 1);
        return {
          files: [
            {
              path: `${nm}.vue`,
              data: `<template>\n${body}</template>\n\n<script setup>\n${banner(meta) || '// Static markup. Behaviour was not reconstructed.\n'}</script>\n\n<style scoped>\n${cssSafe(css)}</style>\n`,
            },
          ],
        };
      }
      case 'svelte':
        return {
          files: [
            { path: `${nm}.svelte`, data: `${html(tree, 0)}\n<style>\n${cssSafe(css)}</style>\n` },
          ],
        };
      case 'tailwind':
        return {
          files: [
            {
              path: 'index.html',
              data: `<!DOCTYPE html>\n<html lang="en">\n<head>\n<meta charset="utf-8">\n<meta name="viewport" content="width=device-width, initial-scale=1">\n<script src="https://cdn.tailwindcss.com"></script>\n</head>\n<body>\n${tailwind(tree, 0, { root: true })}</body>\n</html>\n`,
            },
            {
              path: 'NOTE.md',
              data: "Tailwind output uses arbitrary-property utilities ([prop:value]) because computed styles do not map one-to-one onto Tailwind's design tokens. It is valid Tailwind (v3.1+), but verbose; refactor repeated groups into components or @apply by hand. Pseudo-elements (::before/::after) are not representable this way and are omitted.\n",
            },
          ],
        };
      case 'webcomponent': {
        const el = elementName(name);
        const cls = compName(el);
        return {
          files: [
            {
              path: el + '.js',
              data: `${banner(meta)}const tree = ${treeLiteral(tree, 0)};\n\nconst SVG = 'http://www.w3.org/2000/svg';\n\nfunction build([tag, attrs, cls, kids, ns]) {\n  const el = ns ? document.createElementNS(SVG, tag) : document.createElement(tag);\n  if (cls) el.setAttribute('class', cls);\n  for (const [name, value] of Object.entries(attrs)) el.setAttribute(name, value);\n  el.append(...kids.map((k) => (typeof k === 'string' ? document.createTextNode(k) : build(k))));\n  return el;\n}\n\nconst template = document.createElement('template');\nconst style = document.createElement('style');\nstyle.textContent = ${JSON.stringify(css)};\ntemplate.content.append(style, build(tree));\n\nclass ${cls} extends HTMLElement {\n  constructor() {\n    super();\n    this.attachShadow({ mode: 'open' }).append(template.content.cloneNode(true));\n  }\n}\n\ncustomElements.define('${el}', ${cls});\n`,
            },
          ],
        };
      }
      case 'react-project': {
        const body = jsx(tree, 2);
        const pkg = elementName(name);
        const cmp = nm;
        return {
          files: [
            {
              path: 'package.json',
              data:
                JSON.stringify(
                  {
                    name: pkg,
                    private: true,
                    version: '0.0.0',
                    type: 'module',
                    scripts: { dev: 'vite', build: 'vite build', preview: 'vite preview' },
                    dependencies: { react: '^18.3.1', 'react-dom': '^18.3.1' },
                    devDependencies: { '@vitejs/plugin-react': '^4.3.1', vite: '^5.4.10' },
                  },
                  null,
                  2
                ) + '\n',
            },
            {
              path: 'index.html',
              data: `<!doctype html>\n<html lang="en">\n<head>\n  <meta charset="utf-8">\n  <meta name="viewport" content="width=device-width, initial-scale=1">\n  <title>${esc(name)}</title>\n</head>\n<body>\n  <div id="root"></div>\n  <script type="module" src="/src/main.jsx"></script>\n</body>\n</html>\n`,
            },
            {
              path: 'vite.config.js',
              data: "import { defineConfig } from 'vite';\nimport react from '@vitejs/plugin-react';\n\nexport default defineConfig({ plugins: [react()] });\n",
            },
            {
              path: 'src/main.jsx',
              data: `import { StrictMode } from 'react';\nimport { createRoot } from 'react-dom/client';\nimport ${cmp} from './${cmp}.jsx';\n\ncreateRoot(document.getElementById('root')).render(\n  <StrictMode>\n    <${cmp} />\n  </StrictMode>\n);\n`,
            },
            {
              path: `src/${cmp}.jsx`,
              data: `${banner(meta)}import './${cmp}.css';\n\nexport default function ${cmp}() {\n  return (\n${body.replace(/\n$/, '')}\n  );\n}\n`,
            },
            { path: `src/${cmp}.css`, data: css },
          ],
        };
      }
      case 'json':
        return {
          files: [{ path: 'structure.json', data: JSON.stringify({ tree, css }, null, 2) }],
        };
      default:
        throw new Error('Unknown target: ' + target);
    }
  }

  // The files for a component download: the target's code plus a README that says where the
  // code came from and how to run it. The README replaces any README the target made itself.
  function componentFiles(rec, target, name, meta) {
    const files = generate(rec, target, name, meta).files.filter((f) => f.path !== 'README.md');
    const el = elementName(name);
    const usage = {
      react: `Import the component in a React project and copy \`${compName(name)}.css\` next to it.`,
      vue: `Use \`${compName(name)}.vue\` as a single-file component in a Vue 3 project.`,
      webcomponent: `Add \`<script type="module" src="${el}.js"></script>\` to a page, then use \`<${el}></${el}>\` where the component goes.`,
      'react-project': 'Run `npm install`, then `npm run dev` to open it. `npm run build` writes a production copy to `dist/`.',
    }[target];
    const lines = [
      `# ${compName(name)}`,
      '',
      meta ? `Generated by DevForge ${oneLine(meta.tool)} from \`${oneLine(meta.source)}\` on ${oneLine(meta.page)}.` : 'Generated code.',
      '',
      'The markup and CSS come from the computed styles of the element as the browser drew it. Event handlers, scripts and state were not copied. Compare the result with the original before you use it.',
      '',
      usage,
      '',
    ];
    files.push({ path: 'README.md', data: lines.join('\n') });
    return { files };
  }
  return { generate, componentFiles, html, page, compName, elementName };
})();
if (typeof module !== 'undefined') module.exports = DFGen;
